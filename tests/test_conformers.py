class TestRmsdAndDedupe(unittest.TestCase):
    def setUp(self):
        if not os.path.exists(TRJ):
            self.skipTest("fixture absent")
        self.frames = conformers.parse_trajectory(_trj())

    def test_rmsd_of_a_structure_with_itself_is_zero(self):
        a = self.frames[0]["atoms"]
        self.assertAlmostEqual(conformers.rmsd(a, a), 0.0, places=9)

    def test_rmsd_is_invariant_to_translation_and_rotation(self):
        """If it were not, dedupe would keep every frame and the ensemble would be meaningless."""
        import math
        a = self.frames[3]["atoms"]
        c, s = math.cos(0.9), math.sin(0.9)
        moved = [(sym, x * c - y * s + 7.0, x * s + y * c - 3.0, z + 11.0)
                 for sym, x, y, z in a]
        self.assertAlmostEqual(conformers.rmsd(a, moved), 0.0, places=6)

    def test_rmsd_of_genuinely_different_frames_is_not_zero(self):
        self.assertGreater(conformers.rmsd(self.frames[0]["atoms"],
                                           self.frames[10]["atoms"]), 0.05)

    def test_rmsd_refuses_mismatched_species_rather_than_returning_a_number(self):
        """🔴 It does NO atom matching. Silently comparing atom i with atom i would be worse."""
        a = self.frames[0]["atoms"]
        swapped = [a[1], a[0]] + list(a[2:])
        self.assertRaises(ValueError, conformers.rmsd, a, swapped)
        self.assertRaises(ValueError, conformers.rmsd, a, a[:-1])

    def test_dedupe_collapses_identical_structures(self):
        cands = [dict(self.frames[0], index=0), dict(self.frames[0], index=1)]
        unique, mapping = conformers.dedupe(cands)
        self.assertEqual(len(unique), 1)
        self.assertEqual(mapping["n_in"], 2)
        self.assertEqual(mapping["n_unique"], 1)

    def test_dedupe_keeps_distinct_structures(self):
        cands = [dict(self.frames[i], index=i) for i in (0, 5, 10, 15)]
        unique, _ = conformers.dedupe(cands)
        self.assertGreater(len(unique), 1)

    def test_dedupe_reports_its_hyperparameters_with_the_result(self):
        _, mapping = conformers.dedupe([dict(self.frames[0], index=0)])
        self.assertIn("rmsd_threshold_ang", mapping)
        self.assertTrue(mapping["_thresholds_are_coder_chosen"])

    def test_a_conformer_with_no_energy_is_never_silently_dropped(self):
        cands = [dict(self.frames[0], index=0),
                 {"index": 99, "atoms": self.frames[0]["atoms"], "energy_hartree": None}]
        unique, _ = conformers.dedupe(cands)
        self.assertIn(99, [u["index"] for u in unique],
                      "'we could not read its energy' is not 'it is a duplicate'")


class TestPromotionTakesTheWholeWindow(unittest.TestCase):
    """§37.2.4-2 — and it is what keeps this inside §16.1-B2."""

    def _cands(self, offsets_ev):
        base = -20.5
        return [{"index": i, "atoms": [("C", 0.0, 0.0, 0.0)],
                 "energy_hartree": base + units.ev_to_hartree(dE)}
                for i, dE in enumerate(offsets_ev)]

