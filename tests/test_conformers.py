class TestMetadynInputIsTheDeckThatActuallyRan(unittest.TestCase):
    """🔴 The strongest check available on an input builder: byte-identity with a deck that ran."""

    def test_generated_deck_matches_the_fixture_deck(self):
        if not os.path.exists(INP):
            self.skipTest("fixture absent")
        with open(INP) as fh:
            real = fh.read()
        self.assertEqual(conformers.metadyn_input().strip(), real.strip(),
                         "the generated xcontrol deck no longer matches the one that produced "
                         "the fixture trajectory -- either a parameter moved in config, or the "
                         "builder drifted from a deck we know xtb accepts")

    def test_every_parameter_comes_from_config(self):
        """A hyperparameter written in code is a hyperparameter nobody reports."""
        cfg = config.load("b0_conformers.json")
        m = cfg["metadynamics"]
        deck = conformers.metadyn_input()
        for key, token in (("md_time_ps", "time="), ("md_temp_k", "temp="),
                           ("kpush", "kpush="), ("alp", "alp=")):
            self.assertIn("%s%s" % (token, m[key]), deck)

    def test_the_config_labels_the_parameters_as_unvalidated(self):
        """§37.2.3: the risk of re-implementing CREST is exactly these hyperparameters."""
        note = config.load("b0_conformers.json")["metadynamics"]["_parameter_source"]
        self.assertIn("CODER-CHOSEN", note)
        self.assertIn("NOT TUNED", note)

    def test_argv_uses_unpaired_electrons_not_multiplicity(self):
        """xtb's --uhf and Gaussian's multiplicity differ by one, and confusing them is silent."""
        self.assertEqual(conformers.uhf_from_multiplicity(1), 0)
        self.assertEqual(conformers.uhf_from_multiplicity(2), 1)
        self.assertRaises(ValueError, conformers.uhf_from_multiplicity, 0)
        argv = conformers.metadyn_argv("/x/xtb", "s.xyz", charge=1,
                                       uhf=conformers.uhf_from_multiplicity(1),
                                       input_path="i.inp")
        self.assertEqual(argv[argv.index("--uhf") + 1], "0")
        self.assertEqual(argv[argv.index("--chrg") + 1], "1")


class TestRunHealthIsNotTheBanner(unittest.TestCase):
    """🔴🔴 The trap measured on the real binary this session."""

    def _frames(self):
        return conformers.parse_trajectory(_trj())

    def setUp(self):
        if not os.path.exists(TRJ):
            self.skipTest("fixture absent")

    def test_absent_banner_in_stdout_does_not_make_a_good_run_a_failure(self):
        """🔴 xtb writes the banner to STDERR. Checking stdout fails EVERY run, silently."""
        h = conformers.xtb_health(stdout="...timings...", stderr="normal termination of xtb",
                                  returncode=0, frames=self._frames())
        self.assertTrue(h["usable"],
                        "a run with 20 parsed frames was called unusable because the success "
                        "banner was not in stdout -- it is never in stdout")
        self.assertTrue(h["banner_seen"], "the banner must be sought in BOTH streams")

    def test_a_present_banner_does_not_certify_a_run_with_no_frames(self):
        h = conformers.xtb_health(stdout="", stderr="normal termination of xtb",
                                  returncode=0, frames=[])
        self.assertFalse(h["usable"])
        self.assertTrue(h["banner_seen"])

    def test_the_thermostat_excursion_is_recorded_but_is_not_a_failure(self):
        h = conformers.xtb_health(stdout="T : 658.79\n thermostating problem\n",
                                  stderr="normal termination of xtb",
                                  returncode=0, frames=self._frames())
        self.assertTrue(h["usable"])
        self.assertIn("thermostating problem", h["soft_warnings"])
        self.assertIn("temperature the ensemble was sampled at", " ".join(h["warnings"]))

    def test_an_unusable_run_points_at_the_stream_trap_in_its_own_message(self):
        h = conformers.xtb_health(stdout="", stderr="", returncode=0, frames=[])
        self.assertIn("stderr", " ".join(h["warnings"]),
                      "an unusable verdict must name the stream trap, or the next person spends "
                      "the afternoon concluding that xtb is broken")

    def test_the_criterion_is_stated_in_the_output(self):
        h = conformers.xtb_health(frames=self._frames())
        self.assertIn("NOT the banner", h["criterion"])


