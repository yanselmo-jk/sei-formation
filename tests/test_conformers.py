class TestTemperatureIsTwoFieldsNeverOne(unittest.TestCase):
    """🔴 MD engines do not deliver the requested temperature, and the direction is engine-specific.

    Fixtures are three REAL runs differing only in the two variables under test. See
    tests/fixtures/PROVENANCE.md for the full decomposition.
    """

    def _trace(self, tag):
        path = os.path.join(FIXTURES, "xtb_T_trace_%s.txt" % tag)
        if not os.path.exists(path):
            self.skipTest("fixture absent")
        with open(path) as fh:
            return fh.read()

    def test_both_fields_are_emitted(self):
        r = conformers.temperature_report(400.0, self._trace("mtd_preoptimised"))
        self.assertEqual(r["temperature_requested_k"], 400.0)
        self.assertIsNotNone(r["temperature_measured_k"])
        self.assertNotEqual(r["temperature_requested_k"], r["temperature_measured_k"],
                            "requested and measured came out identical -- if a `temperature` "
                            "field is recording the setpoint, nobody will ever know")

    def test_the_thermostat_itself_is_correct(self):
        """🔴 THE FINDING. Plain MD from the optimised structure HOLDS ITS SETPOINT."""
        r = conformers.temperature_report(400.0, self._trace("plainmd"))
        self.assertLess(abs(r["temperature_measured_k"] - 400.0), 40.0,
                        "plain MD no longer holds its setpoint -- the conclusion that the "
                        "thermostat is correct rested on exactly this")
        self.assertEqual(r["warnings"], [])

    def test_the_bias_potential_is_what_raises_the_temperature(self):
        """Same optimised geometry, same $md block; the ONLY difference is $metadyn."""
        plain = conformers.temperature_report(400.0, self._trace("plainmd"))
        mtd = conformers.temperature_report(400.0, self._trace("mtd_preoptimised"))
        self.assertGreater(mtd["temperature_measured_k"] - plain["temperature_measured_k"], 50.0,
                           "the bias potential no longer shows a temperature effect -- the whole "
                           "diagnostic conclusion would need re-running")

    def test_the_idealised_start_adds_a_further_excursion_on_top(self):
        ideal = conformers.temperature_report(400.0, self._trace("mtd_idealised"))
        preopt = conformers.temperature_report(400.0, self._trace("mtd_preoptimised"))
        self.assertGreater(ideal["temperature_measured_k"], preopt["temperature_measured_k"],
                           "pre-optimising no longer reduces the temperature -- ADR-067's "
                           "'check the input first' would lose its instance here")

    def test_t_eff_is_not_a_constant(self):
        """🔴 It must be measured per run, never applied as a stored factor."""
        ratios = [conformers.temperature_report(400.0, self._trace(t))["t_eff_over_t_set"]
                  for t in ("mtd_idealised", "mtd_preoptimised", "plainmd")]
        self.assertGreater(max(ratios) - min(ratios), 0.3,
                           "the three conditions gave nearly the same T_eff/T_set, which would "
                           "make a stored factor defensible. It was 1.70 / 1.22 / 0.96.")

    def test_an_off_setpoint_metadynamics_run_is_flagged_but_not_called_a_defect(self):
        r = conformers.temperature_report(400.0, self._trace("mtd_idealised"))
        joined = " ".join(r["warnings"])
        self.assertIn("EXPECTED, not a defect", joined)
        self.assertIn("not a rate at a defined temperature", joined)

    def test_an_unparseable_log_says_the_temperature_is_unknown(self):
        r = conformers.temperature_report(400.0, "no md table here")
        self.assertIsNone(r["temperature_measured_k"])
        self.assertIn("temperature_not_measured", " ".join(r["warnings"]))


