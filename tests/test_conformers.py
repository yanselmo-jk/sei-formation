class TestDissociationIsCountedNotDiscarded(unittest.TestCase):
    def setUp(self):
        if not os.path.exists(TRJ):
            self.skipTest("fixture absent")
        self.frames = conformers.parse_trajectory(_trj())

    def test_the_real_intact_frames_are_classified_intact(self):
        c = conformers.classify_complex(self.frames[0]["atoms"], n_ligands_expected=1)
        self.assertEqual(c["classification"], conformers.CLASS_INTACT)
        self.assertEqual(c["n_ligand_fragments"], 1)

    def test_a_dissociated_ligand_is_detected_and_named_as_such(self):
        atoms = self.frames[0]["atoms"]
        pulled = [(s, x, y + (25.0 if s == "Li" else 0.0), z) for s, x, y, z in atoms]
        c = conformers.classify_complex(pulled, n_ligands_expected=1)
        self.assertEqual(c["classification"], conformers.CLASS_DISSOCIATED)
        self.assertEqual(c["uncoordinated_fragments"], 1)

    def test_fragmentation_and_dissociation_are_different_classes(self):
        """🔴 A ligand that BROKE and a ligand that DRIFTED OFF mean different things."""
        atoms = self.frames[0]["atoms"]
        # Rip one hydrogen far away: the ligand is now two covalent fragments.
        broken = list(atoms)
        for i, a in enumerate(broken):
            if a[0] == "H":
                broken[i] = (a[0], a[1] + 12.0, a[2], a[3])
                break
        c = conformers.classify_complex(broken, n_ligands_expected=1)
        self.assertEqual(c["classification"], conformers.CLASS_FRAGMENTED)
        self.assertNotEqual(c["classification"], conformers.CLASS_DISSOCIATED)

    def test_a_structure_without_the_cation_is_unclassified_not_intact(self):
        """🔴 Rule 18: what cannot be classified is held out, never counted as intact."""
        no_li = [a for a in self.frames[0]["atoms"] if a[0] != "Li"]
        c = conformers.classify_complex(no_li, n_ligands_expected=1)
        self.assertIsNone(c["classification"])
        self.assertIn("classification_impossible", " ".join(c["warnings"]))

    def test_transient_stretches_in_the_real_trajectory_are_visible(self):
        """The real run has a frame at min(Li-X) = 2.688 A, past the 2.4 A contact cutoff.

        🔒 This is why classification runs on OPTIMISED structures, not raw MD frames -- and the
        number is asserted so the fixture cannot be swapped for a tamer one.
        """
        dmax = max(conformers.classify_complex(f["atoms"], 1)["min_contact_ang"]
                   for f in self.frames)
        self.assertGreater(dmax, 2.4,
                           "the fixture no longer contains a transient excursion past the "
                           "contact cutoff -- it was the reason for optimising before classifying")


